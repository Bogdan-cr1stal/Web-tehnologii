// Цикл для створення 5 абзаців
for (let i = 1; i <= 5; i++) {
    // Обчислення ширини від 200px до 600px крок за кроком (200, 300, 400, 500, 600)
    let width = 200 + (i - 1) * 100;
    
    // Виведення за допомогою методу document.write() із заданням ширини через атрибут style
    document.write(`<p style="width: ${width}px;">Абзац ${i}</p>`);
}